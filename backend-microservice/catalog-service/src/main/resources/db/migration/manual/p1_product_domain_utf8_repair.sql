-- Repairs only the stable P1 demo rows that older Windows PowerShell imports
-- encoded as ASCII. No user-created catalog row is selected by these updates.
SET NAMES utf8mb4;
START TRANSACTION;

UPDATE category SET name = CASE id
    WHEN '32000000-0000-0000-0000-000000000101' THEN 'Thời trang'
    WHEN '32000000-0000-0000-0000-000000000102' THEN 'Giày'
    WHEN '32000000-0000-0000-0000-000000000103' THEN 'Giày chạy bộ'
    WHEN '32000000-0000-0000-0000-000000000104' THEN 'Điện tử'
    WHEN '32000000-0000-0000-0000-000000000105' THEN 'Điện thoại'
    WHEN '32000000-0000-0000-0000-000000000108' THEN 'Phụ kiện điện thoại'
    WHEN '32000000-0000-0000-0000-000000000106' THEN 'Mỹ phẩm'
END WHERE id IN (
    '32000000-0000-0000-0000-000000000101','32000000-0000-0000-0000-000000000102',
    '32000000-0000-0000-0000-000000000103','32000000-0000-0000-0000-000000000104',
    '32000000-0000-0000-0000-000000000105','32000000-0000-0000-0000-000000000108',
    '32000000-0000-0000-0000-000000000106'
);

UPDATE product_attribute_definition SET name = CASE code
    WHEN 'ATTR-BRAND' THEN 'Thương hiệu'
    WHEN 'ATTR-ORIGIN' THEN 'Xuất xứ'
    WHEN 'ATTR-MATERIAL' THEN 'Chất liệu'
    WHEN 'ATTR-SOLE-TYPE' THEN 'Loại đế'
    WHEN 'ATTR-HEEL-DROP' THEN 'Độ drop'
    WHEN 'ATTR-CHIP' THEN 'Chip xử lý'
    WHEN 'ATTR-BATTERY' THEN 'Dung lượng pin'
    WHEN 'ATTR-WARRANTY' THEN 'Bảo hành'
    WHEN 'ATTR-ACTIVE-INGREDIENT' THEN 'Thành phần chính'
    WHEN 'ATTR-CONCENTRATION' THEN 'Nồng độ'
    WHEN 'ATTR-SKIN-TYPE' THEN 'Loại da phù hợp'
    WHEN 'ATTR-FABRIC-SELLER' THEN 'Chất liệu vải'
END WHERE code IN ('ATTR-BRAND','ATTR-ORIGIN','ATTR-MATERIAL','ATTR-SOLE-TYPE','ATTR-HEEL-DROP','ATTR-CHIP','ATTR-BATTERY','ATTR-WARRANTY','ATTR-ACTIVE-INGREDIENT','ATTR-CONCENTRATION','ATTR-SKIN-TYPE','ATTR-FABRIC-SELLER');
UPDATE product_attribute_definition SET default_unit = 'tháng' WHERE code = 'ATTR-WARRANTY';

UPDATE product_attribute_option SET value = CASE id
    WHEN '42000000-0000-0000-0000-000000000004' THEN 'Việt Nam'
    WHEN '42000000-0000-0000-0000-000000000005' THEN 'Hoa Kỳ'
    WHEN '42000000-0000-0000-0000-000000000006' THEN 'Hàn Quốc'
    WHEN '42000000-0000-0000-0000-000000000007' THEN 'Việt Nam - nội địa'
    WHEN '42000000-0000-0000-0000-000000000008' THEN 'Đế foam'
    WHEN '42000000-0000-0000-0000-000000000009' THEN 'Đế cao su'
    WHEN '42000000-0000-0000-0000-000000000010' THEN 'Da dầu'
    WHEN '42000000-0000-0000-0000-000000000011' THEN 'Da khô'
    WHEN '42000000-0000-0000-0000-000000000012' THEN 'Da hỗn hợp'
    WHEN '42000000-0000-0000-0000-000000000013' THEN 'Da nhạy cảm'
END WHERE id BETWEEN '42000000-0000-0000-0000-000000000004' AND '42000000-0000-0000-0000-000000000013';

UPDATE product SET
    name = 'Giày chạy AeroRun Pro',
    description = 'Hai trục Màu sắc và Kích cỡ'
WHERE id = '37000000-0000-0000-0000-000000000001';
UPDATE product SET description = 'Hai trục Dung lượng và Màu' WHERE id = '37000000-0000-0000-0000-000000000002';
UPDATE product SET description = 'Không trục, dùng default variant' WHERE id = '37000000-0000-0000-0000-000000000003';
UPDATE product SET description = 'Một trục Công suất' WHERE id = '37000000-0000-0000-0000-000000000004';
UPDATE product_attribute_value SET value_text = 'Vải mesh'
WHERE product_id = '37000000-0000-0000-0000-000000000001'
  AND attribute_definition_id = '41000000-0000-0000-0000-000000000003';

UPDATE variant_axis_name_suggestion SET name = CASE normalized_name
    WHEN 'mau sac' THEN 'Màu sắc'
    WHEN 'kich co' THEN 'Kích cỡ'
    WHEN 'dung luong' THEN 'Dung lượng'
    WHEN 'mau' THEN 'Màu'
    WHEN 'cong suat' THEN 'Công suất'
END WHERE normalized_name IN ('mau sac','kich co','dung luong','mau','cong suat');

UPDATE product_variant_axis SET name = CASE id
    WHEN '43000000-0000-0000-0000-000000000001' THEN 'Màu sắc'
    WHEN '43000000-0000-0000-0000-000000000002' THEN 'Kích cỡ'
    WHEN '43000000-0000-0000-0000-000000000003' THEN 'Dung lượng'
    WHEN '43000000-0000-0000-0000-000000000004' THEN 'Màu'
    WHEN '43000000-0000-0000-0000-000000000005' THEN 'Công suất'
END WHERE id IN ('43000000-0000-0000-0000-000000000001','43000000-0000-0000-0000-000000000002','43000000-0000-0000-0000-000000000003','43000000-0000-0000-0000-000000000004','43000000-0000-0000-0000-000000000005');

UPDATE product_variant_axis_value SET value = CASE id
    WHEN '44000000-0000-0000-0000-000000000001' THEN 'Trắng'
    WHEN '44000000-0000-0000-0000-000000000002' THEN 'Đen'
    WHEN '44000000-0000-0000-0000-000000000008' THEN 'Đen'
    WHEN '44000000-0000-0000-0000-000000000009' THEN 'Xanh'
END WHERE id IN ('44000000-0000-0000-0000-000000000001','44000000-0000-0000-0000-000000000002','44000000-0000-0000-0000-000000000008','44000000-0000-0000-0000-000000000009');

